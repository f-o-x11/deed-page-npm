'use strict';
const assert = require('assert');
const fs = require('fs'); const os = require('os'); const path = require('path');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'dp-'));
process.env.XDG_CONFIG_HOME = path.join(tmp, 'cfg');
delete process.env.DEED_PAGE_TOKEN; delete process.env.DEEDPAGE_TOKEN;
const lib = require('../lib/index.js');
fs.mkdirSync(path.join(tmp, 'site/css'), { recursive: true });
fs.writeFileSync(path.join(tmp, 'site/index.html'), '<h1>x</h1>');
fs.writeFileSync(path.join(tmp, 'site/css/a.css'), 'h1{}');
fs.writeFileSync(path.join(tmp, 'site/logo.png'), Buffer.from([0x89, 0x50, 0x4e, 0x47]));
const m = lib.collectFiles(path.join(tmp, 'site'));
assert.strictEqual(m['index.html'], '<h1>x</h1>');
assert.strictEqual(m['css/a.css'], 'h1{}');
assert.deepStrictEqual(m['logo.png'], { base64: 'iVBORw==' });
assert.deepStrictEqual(Object.keys(lib.collectFiles(path.join(tmp, 'site/index.html'))), ['index.html']);
assert.strictEqual(lib.loadToken(), null);
const p = lib.saveToken('deed_tok_test123');
assert.strictEqual((fs.statSync(p).mode & 0o777), 0o600);
assert.strictEqual(lib.loadToken(), 'deed_tok_test123');
process.env.DEED_PAGE_TOKEN = 'deed_tok_env';
assert.strictEqual(lib.loadToken(), 'deed_tok_env');
assert.deepStrictEqual(lib.redact({ token: 'deed_tok_abc-1' }), { token: '<redacted>' });
console.log('offline tests passed');
